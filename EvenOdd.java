public class EvenOdd {
    public static void main(String[] args) {
        // Print even numbers
        for (int i = 2; i <= 100; i += 2) {
            System.out.print(i + " ");
        }

        System.out.println();

        // Print odd numbers
        for (int i = 1; i <= 100; i += 2) {
            System.out.print(i + " ");
        }
    }
}